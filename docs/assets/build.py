#!/usr/bin/env python3
"""Build the README artwork in docs/assets from its sources.

Hand-written sources (edit these):
  mark.txt       the fastvol mark: the pixel "fv" on its tile, 24x16 ('#' glyph, '+' tile,
                 '.' transparent). The row count stays even: `fvol --version` prints the same
                 grid in a terminal with half blocks, two pixel rows per line (src/cli/banner.rs
                 includes this file).
  favicon.txt    the mark squeezed onto a 16x16 tile for favicons
  WORDMARK below the pixel-italic "fastvol" lettering (12 rows)

Generated by this script (do not edit by hand):
  mark.svg, favicon.svg          the grids as crisp SVG paths
  wordmark.svg, wordmark-dark.svg
                                 the lettering for light and dark backgrounds
  logo.svg, logo-dark.svg        mark + wordmark, horizontal lockups (a 16-row pixel grid: show them at
                                 whole multiples, 6x = the width/height the SVG declares, as in the README)
  benchmark.svg, benchmark-dark.svg
                                 the README's headline chart, from bench/local/summary.json
                                 (bench/scripts/bench_local_report.py)
  badges/*.svg                   the README's rust, release and license badges, from Cargo.toml
                                 (the CI status badge next to them is GitHub's own)
  png/*.png                      previews, only with --png (needs a chromium on PATH)

Usage: python3 docs/assets/build.py [--png]

Standard library only.
"""

import json
import math
import os
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
SUMMARY = os.environ.get("FASTVOL_BENCH_SUMMARY", os.path.join(ROOT, "bench", "local", "summary.json"))

GLYPH = "#46e67a"       # phosphor green: the fv, and fastvol's colour on dark backgrounds
TILE = "#123020"        # the mark's tile
GREEN = "#1f9e57"       # the glyph green darkened for light backgrounds (3.4:1 on white)
INK_LIGHT = "#1f2328"   # GitHub's light-theme text colour
INK_DARK = "#f0f6fc"    # GitHub's dark-theme text colour

FONT = "-apple-system, BlinkMacSystemFont, 'Segoe UI', 'Noto Sans', Helvetica, Arial, sans-serif"


def read(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        return f.read()


def write(name, text):
    path = os.path.join(HERE, name)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, ROOT))


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


