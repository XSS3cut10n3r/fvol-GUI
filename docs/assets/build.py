#!/usr/bin/env python3
"""Build the README artwork in docs/assets from its sources.

Hand-written sources (edit these):
  mascot.svg     the ferret mark: a flat, frontal masked face; square, transparent, 32 px and up
  favicon.svg    the same face redrawn on a 32-unit pixel grid for 16 to 48 px
  wordmark.svg   the "fastvol" lettering for light backgrounds

Generated by this script (do not edit by hand):
  wordmark-dark.svg              the wordmark for dark backgrounds
  logo.svg, logo-dark.svg        mascot + wordmark, horizontal lockups
  benchmark.svg, benchmark-dark.svg
                                 the README's headline chart; every number is parsed from the
                                 headline tables of bench/vm/BENCHMARKS.md
  badges/*.svg                   static README badges (no external badge service)
  png/*.png                      previews, only with --png (needs a chromium on PATH)

Usage: python3 docs/assets/build.py [--png]

Standard library only. The mascot is the one source of the ferret; the wordmark is kept apart
from it so that the name can change without touching the mascot.
"""

import math
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
BENCHMARKS = os.path.join(ROOT, "bench", "vm", "BENCHMARKS.md")

COPPER = "#e0662b"
INK_LIGHT = "#1f2328"   # GitHub's light-theme text colour
INK_DARK = "#f0f6fc"    # GitHub's dark-theme text colour

FONT = "-apple-system, BlinkMacSystemFont, 'Segoe UI', 'Noto Sans', Helvetica, Arial, sans-serif"


def read(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        return f.read()


def write(name, text):
    path = os.path.join(HERE, name)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, ROOT))


def svg_body(text):
    """The markup inside the root <svg> element, without comments."""
    inner = re.search(r"<svg[^>]*>(.*)</svg>", text, re.S).group(1)
    inner = re.sub(r"<!--.*?-->", "", inner, flags=re.S)
    return "\n".join(line for line in inner.splitlines() if line.strip())


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


