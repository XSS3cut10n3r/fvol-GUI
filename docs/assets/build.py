# Wordmark and logo lockups

GENERATED = "<!-- Generated by docs/assets/build.py from mark.txt / favicon.txt / WORDMARK. Do not edit. -->"

# The pixel-italic wordmark: one list of rows per letter, 12 rows, baseline = last row; each row
# is sheared right by 1 px per SHEAR rows above the baseline, letters TRACK px apart.
WORDMARK = {
    "f": ["..####", ".#####", ".##...", ".##...", "######", "######",
          ".##...", ".##...", ".##...", ".##...", ".##...", ".##..."],
    "a": ["", "", "", "", "######.", "#######", ".....##", ".######",
          "#######", "##...##", "#######", ".######"],
    "s": ["", "", "", "", ".######", "#######", "##.....", "######.",
          ".######", ".....##", "#######", "######."],
    "t": ["", ".##...", ".##...", ".##...", "######", "######",
          ".##...", ".##...", ".##...", ".##...", ".#####", "..####"],
    "v": ["", "", "", "", "##...##", "##...##", "##...##", "##...##",
          ".##.##.", ".##.##.", "..###..", "..###.."],
    "o": ["", "", "", "", ".#####.", "#######", "##...##", "##...##",
          "##...##", "##...##", "#######", ".#####."],
    "l": ["##"] * 12,
}
SHEAR = 4
TRACK = 2
GAP = 6  # between the mark and the wordmark


def read_grid(name):
    rows = [r.rstrip("\n") for r in read(name).splitlines() if r.strip()]
    if len({len(r) for r in rows}) != 1:
        sys.exit(f"build.py: {name}: rows of different lengths")
    if len(rows) % 2:
        sys.exit(f"build.py: {name}: the row count must be even (two pixel rows per terminal line)")
    return rows


def cells_of(rows, chars):
    return {(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c in chars}


def pixel_path(cells, ox=0, oy=0):
    """Rectangles covering `cells`: horizontal runs, stacked where the next rows repeat them."""
    runs = {}
    for x, y in sorted(cells, key=lambda c: (c[1], c[0])):
        row = runs.setdefault(y, [])
        if row and row[-1][0] + row[-1][1] == x:
            row[-1][1] += 1
        else:
            row.append([x, 1])
    done, d = set(), []
    for y in sorted(runs):
        for x, w in runs[y]:
            if (x, w, y) in done:
                continue
            h = 1
            while [x, w] in runs.get(y + h, []):
                done.add((x, w, y + h))
                h += 1
            d.append(f"M{x + ox} {y + oy}h{w}v{h}h-{w}z")
    return "".join(d)


def pixel_svg(w, h, scale, body):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w * scale}" '
            f'height="{h * scale}" role="img" aria-label="fastvol" shape-rendering="crispEdges">\n'
            f"{GENERATED}\n{body}</svg>\n")


def mark_body(rows, ox=0):
    return (f'<path fill="{TILE}" d="{pixel_path(cells_of(rows, "#+"), ox)}"/>\n'
            f'<path fill="{GLYPH}" d="{pixel_path(cells_of(rows, "#"), ox)}"/>\n')


def wordmark_cells():
    cells, x0, n = set(), 0, 12
    for ch in "fastvol":
        glyph = WORDMARK[ch]
        w = max(len(r) for r in glyph)
        for y, r in enumerate(glyph):
            for x, c in enumerate(r):
                if c == "#":
                    cells.add((x0 + x + (n - 1 - y) // SHEAR, y))
        x0 += w + TRACK
    return cells


def build_logos():
    mark, fav = read_grid("mark.txt"), read_grid("favicon.txt")
    mw, mh = len(mark[0]), len(mark)
    write("mark.svg", pixel_svg(mw, mh, 4, mark_body(mark)))
    write("favicon.svg", pixel_svg(len(fav[0]), len(fav), 2, mark_body(fav)))
    word = wordmark_cells()
    ww = max(x for x, _ in word) + 1
    for name, ink in (("wordmark.svg", INK_LIGHT), ("wordmark-dark.svg", INK_DARK)):
        write(name, pixel_svg(ww, 12, 4, f'<path fill="{ink}" d="{pixel_path(word)}"/>\n'))
    # the wordmark spans the f's rows: ascender (its first row) to baseline
    top = next(y for y, r in enumerate(mark) if "#" in r)
    lw = mw + GAP + ww
    for name, ink in (("logo.svg", INK_LIGHT), ("logo-dark.svg", INK_DARK)):
        body = mark_body(mark) + f'<path fill="{ink}" d="{pixel_path(word, mw + GAP, top)}"/>\n'
        write(name, pixel_svg(lw, mh, 6, body))


