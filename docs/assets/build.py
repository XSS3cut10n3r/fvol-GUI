# Wordmark and logo lockups

GENERATED = "<!-- Generated by docs/assets/build.py from mascot.svg and wordmark.svg. Do not edit. -->"


def build_logos():
    wordmark = read("wordmark.svg")
    dark = wordmark.replace(INK_LIGHT, INK_DARK)
    dark = dark.replace("Hand-written source for light backgrounds", "Dark-background variant, generated from wordmark.svg")
    write("wordmark-dark.svg", dark)

    mascot = svg_body(read("mascot.svg"))
    for name, ink in (("logo.svg", INK_LIGHT), ("logo-dark.svg", INK_DARK)):
        words = svg_body(wordmark.replace(INK_LIGHT, ink))
        # The mark (box x 11..117, y 16..112) at 0.74 is centred on the wordmark's ascender-to-
        # baseline span (y 37..100), 16 units of air before the "f" crossbar, 8 of margin all round.
        write(name, f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="-8 25 367 87" role="img" aria-label="fastvol">
{GENERATED}
<g id="mascot" transform="translate(-8.14 21.2) scale(.74)">
{mascot}
</g>
<g id="wordmark" transform="translate(100 0)">
{words}
</g>
</svg>
''')


