# Headline benchmark chart


def parse_benchmarks():
    """{"Windows": (plugins, {row label: {column: cell}}), "Linux": ...} from the headline tables."""
    lines = open(BENCHMARKS, encoding="utf-8").read().splitlines()
    tables = {}
    for i, line in enumerate(lines):
        m = re.match(r"\| (Windows|Linux) \((\d+) plugins\) \|", line)
        if not m or m.group(1) in tables:
            continue
        header = [c.strip() for c in line.strip().strip("|").split("|")]
        rows = {}
        j = i + 2
        while j < len(lines) and lines[j].startswith("|"):
            cells = [c.strip() for c in lines[j].strip().strip("|").split("|")]
            rows[cells[0]] = dict(zip(header[1:], cells[1:]))
            j += 1
        tables[m.group(1)] = (int(m.group(2)), rows)
    for os_name in ("Windows", "Linux"):
        if os_name not in tables:
            sys.exit(f"build.py: no '| {os_name} (N plugins) |' headline table in {BENCHMARKS}")
    return tables


def seconds(cell):
    m = re.fullmatch(r"([\d,.]+) (s|ms)", cell.strip())
    if not m:
        sys.exit(f"build.py: cannot read a time from {cell!r}")
    v = float(m.group(1).replace(",", ""))
    return v / 1000 if m.group(2) == "ms" else v


def fmt_seconds(v):
    if v >= 1000:
        return f"{v:,.0f} s"
    if v >= 10:
        return f"{v:.1f} s"
    return f"{v:.2f} s"


def speedup(cell, which):
    """'463x / 69.2x' -> '463x' (which=0, total) or '69.2x' (which=1, geo-mean)."""
    return cell.split("/")[which].strip()


CHART_THEMES = {
    "light": dict(bg="#ffffff", border="#d1d9e0", text=INK_LIGHT, text2="#59636e", muted="#6e7781",
                  grid="#e6eaef", accent=GREEN, accent_soft="#8fd9a8", other="#8c959f",
                  other_soft="#c5ccd4"),
    "dark": dict(bg="#0d1117", border="#30363d", text=INK_DARK, text2="#9198a1", muted="#7d8590",
                 grid="#21262d", accent=GLYPH, accent_soft="#2a7a48", other="#848d97",
                 other_soft="#454c56"),
}

PANELS = (
    ("Windows", "Windows 11 x64, 5 GiB raw image"),
    ("Linux", "Ubuntu 24.04, Linux 6.8, 3 GiB ELF core"),
)


def build_chart():
    tables = parse_benchmarks()
    W = 840
    X_TOOL, X_RUN, X0, DECADE = 28, 164, 256, 112.0   # bars: 1 s at X0, 10x per DECADE px
    DECADES = 4                                     # 1 s .. 10,000 s
    ROW, BAR, GROUP_GAP = 22, 12, 8

    def x_of(v):
        return X0 + math.log10(v) * DECADE

    panels = []
    for os_name, image in PANELS:
        plugins, rows = tables[os_name]
        total = rows["total wall (sum of per-plugin best)"]
        speed = rows["speedup vs python: total / geo-mean"]
        py = seconds(total["python"])
        panels.append(dict(
            title=f"{image} · {plugins} plugins",
            tools=[
                ("python volatility3", "other", [("repeat run", py, f"{fmt_seconds(py)}  ({py / 60:.0f} min)", None)]),
                ("vol-rs", "other", [
                    ("first run", seconds(total["vol-rs cold"]), None, None),
                    ("repeat run", seconds(total["vol-rs warm"]), None, None)]),
                ("fastvol", "accent", [
                    ("first run", seconds(total["fastvol cold"]), None, speedup(speed["fastvol cold"], 0)),
                    ("repeat run", seconds(total["fastvol warm"]), None, speedup(speed["fastvol warm"], 0))]),
            ]))

    def render(theme):
        t = CHART_THEMES[theme]
        out = []
        y = 104
        desc = []
        grid_ticks = [10 ** k for k in range(DECADES + 1)]
        for p in panels:
            out.append(f'<text x="{X_TOOL}" y="{y}" class="h">{esc(p["title"])}</text>')
            top = y + 12
            ry = top
            rows_svg = []
            for tool, kind, runs in p["tools"]:
                for k, (run, v, label, factor) in enumerate(runs):
                    cy = ry + ROW / 2
                    if k == 0:
                        cls = "tool b" if kind == "accent" else "tool"
                        ty = ry + len(runs) * ROW / 2
                        rows_svg.append(f'<text x="{X_TOOL}" y="{ty + 4.5:.1f}" class="{cls}">{tool}</text>')
                    rows_svg.append(f'<text x="{X_RUN}" y="{cy + 4.5:.1f}" class="run">{run}</text>')
                    soft = run == "first run"
                    fill = t[kind + ("_soft" if soft else "")]
                    x1 = x_of(v)
                    r = 4
                    yb = cy - BAR / 2
                    rows_svg.append(
                        f'<path fill="{fill}" d="M{X0} {yb:.1f}H{x1 - r:.1f}A{r} {r} 0 0 1 {x1:.1f} {yb + r:.1f}'
                        f'V{yb + BAR - r:.1f}A{r} {r} 0 0 1 {x1 - r:.1f} {yb + BAR:.1f}H{X0}Z"/>')
                    text = label or fmt_seconds(v)
                    vcls = "val b" if kind == "accent" else "val"
                    extra = f'<tspan class="note" dx="8">{factor} faster than python</tspan>' if factor else ""
                    rows_svg.append(f'<text x="{x1 + 7:.1f}" y="{cy + 4.5:.1f}" class="{vcls}">{esc(text)}{extra}</text>')
                    desc.append(f"{p['title']}: {tool} {run} {fmt_seconds(v)}")
                    ry += ROW
                ry += GROUP_GAP
            bottom = ry - GROUP_GAP
            for tick in grid_ticks:
                gx = x_of(tick)
                out.append(f'<path d="M{gx:.1f} {top - 2}V{bottom + 2}" class="grid"/>')
            out.extend(rows_svg)
            y = bottom + 40
        axis_y = y - 18
        for tick in grid_ticks:
            out.append(f'<text x="{x_of(tick):.1f}" y="{axis_y}" class="tick" text-anchor="middle">{tick:,} s</text>')
        foot_y = axis_y + 34
        foot = [
            "Sum of the best wall-clock time of each plugin (5 runs; python 1 or 2), one process per plugin, image in the page cache.",
            "First run: the tool's caches emptied before every run. Repeat run: caches as the previous run left them. Source: bench/vm/BENCHMARKS.md",
        ]
        for k, line in enumerate(foot):
            out.append(f'<text x="{X_TOOL}" y="{foot_y + k * 17}" class="foot">{esc(line)}</text>')
        H = foot_y + 17 + 22
        title = "Total time to run the benchmark suite"
        head = [
            f'<rect x=".5" y=".5" width="{W - 1}" height="{H - 1}" rx="12" fill="{t["bg"]}" stroke="{t["border"]}"/>',
            f'<text x="{X_TOOL}" y="42" class="title">{title}</text>',
            f'<text x="{X_TOOL}" y="64" class="sub">Each plugin run once as its own process, and the times added up. Log scale: each gridline is 10x. Shorter is faster.</text>',
        ]
        style = f"""<style>
text{{font-family:{FONT};fill:{t['text']}}}
.title{{font-size:17px;font-weight:600}}
.sub{{font-size:12.5px;fill:{t['text2']}}}
.h{{font-size:13px;font-weight:600}}
.tool{{font-size:13px;fill:{t['text2']}}}
.run{{font-size:12px;fill:{t['muted']}}}
.val{{font-size:12px;fill:{t['text2']};paint-order:stroke;stroke:{t['bg']};stroke-width:5px;stroke-linejoin:round}}
.b{{font-weight:600;fill:{t['text']}}}
.note{{font-weight:400;fill:{t['muted']}}}
.tick{{font-size:11px;fill:{t['muted']}}}
.foot{{font-size:11px;fill:{t['muted']}}}
.grid{{stroke:{t['grid']};stroke-width:1;fill:none}}
</style>"""
        return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-labelledby="t d">\n'
                f"<!-- Generated by docs/assets/build.py from bench/vm/BENCHMARKS.md. Do not edit. -->\n"
                f'<title id="t">{title}</title>\n<desc id="d">{esc("; ".join(desc))}. Source: bench/vm/BENCHMARKS.md.</desc>\n'
                + style + "\n" + "\n".join(head + out) + "\n</svg>\n")

    write("benchmark.svg", render("light"))
    write("benchmark-dark.svg", render("dark"))


