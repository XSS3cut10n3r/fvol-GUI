def text_width(s, size):
    return sum(_WIDTH.get(ch, 0.6) for ch in s) * size


def badges():
    """(file, label, value, value colour): white text at 5:1 or more on each colour. The shape
    (20 px high, 3 px radius, #30363d label) matches the CI status badge GitHub draws."""
    with open(os.path.join(ROOT, "Cargo.toml"), "rb") as f:
        pkg = tomllib.load(f)["package"]
    return (
        ("rust", "rust", f"{pkg['rust-version']}+", "#b7410e"),
        ("release", "release", f"v{pkg['version']}", "#0969da"),
        ("license", "license", "VSL 1.0", "#8250df"),
    )


def build_badges():
    size, h, pad = 11, 20, 7
    for name, label, value, colour in badges():
        lw = round(text_width(label, size)) + 2 * pad
        vw = round(text_width(value, size)) + 2 * pad
        w = lw + vw
        tl = round(text_width(label, size), 1)
        tv = round(text_width(value, size), 1)
        write(f"badges/{name}.svg", f'''<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" role="img" aria-label="{esc(label)}: {esc(value)}">
<title>{esc(label)}: {esc(value)}</title>
<clipPath id="r"><rect width="{w}" height="{h}" rx="3"/></clipPath>
<g clip-path="url(#r)">
<rect width="{lw}" height="{h}" fill="#30363d"/>
<rect x="{lw}" width="{vw}" height="{h}" fill="{colour}"/>
</g>
<g fill="#fff" font-family="Helvetica Neue, Helvetica, Arial, Liberation Sans, sans-serif" font-size="{size}">
<text x="{pad}" y="14" textLength="{tl}" lengthAdjust="spacingAndGlyphs">{esc(label)}</text>
<text x="{lw + pad}" y="14" textLength="{tv}" lengthAdjust="spacingAndGlyphs">{esc(value)}</text>
</g>
</svg>
''')


