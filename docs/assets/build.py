# PNG previews


def render_pngs():
    chromium = shutil.which("chromium") or shutil.which("chromium-browser") or shutil.which("google-chrome")
    if not chromium:
        sys.exit("build.py: --png needs chromium on PATH")
    jobs = (
        # (output, svg, css width, css height, background, device scale)
        ("png/mark-384.png", "mark.svg", 384, 256, "transparent", 1),
        ("png/favicon-16.png", "favicon.svg", 16, 16, "transparent", 1),
        ("png/favicon-32.png", "favicon.svg", 32, 32, "transparent", 1),
        ("png/favicon-48.png", "favicon.svg", 48, 48, "transparent", 1),
        ("png/favicon-64.png", "favicon.svg", 64, 64, "transparent", 1),
        ("png/logo.png", "logo.svg", None, None, "#ffffff", 2),
        ("png/logo-dark.png", "logo-dark.svg", None, None, "#0d1117", 2),
        ("png/benchmark.png", "benchmark.svg", None, None, "transparent", 2),
        ("png/benchmark-dark.png", "benchmark-dark.svg", None, None, "transparent", 2),
    )
    with tempfile.TemporaryDirectory() as tmp:
        for out, svg, w, h, bg, scale in jobs:
            if w is None:
                m = re.search(r'width="(\d+)" height="(\d+)"', read(svg))
                w, h = int(m.group(1)), int(m.group(2))
            page = os.path.join(tmp, "page.html")
            with open(page, "w") as f:
                f.write(f'<!doctype html><html><head><style>html,body{{margin:0;background:{bg}}}'
                        f'img{{display:block;width:{w}px;height:{h}px}}</style></head>'
                        f'<body><img src="file://{os.path.join(HERE, svg)}"></body></html>')
            target = os.path.join(HERE, out)
            os.makedirs(os.path.dirname(target), exist_ok=True)
            subprocess.run([chromium, "--headless=new", "--disable-gpu", "--no-sandbox", "--hide-scrollbars",
                            "--default-background-color=00000000", f"--force-device-scale-factor={scale}",
                            f"--window-size={w},{h}", f"--screenshot={target}", f"file://{page}"],
                           check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            print("wrote", os.path.relpath(target, ROOT))


def main():
    build_logos()
    build_chart()
    build_badges()
    if "--png" in sys.argv[1:]:
        render_pngs()


if __name__ == "__main__":
    main()
