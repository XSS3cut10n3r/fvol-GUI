    const FHCRC: u8 = 0x02;
    const FEXTRA: u8 = 0x04;
    const FNAME: u8 = 0x08;
    const FCOMMENT: u8 = 0x10;

    /// Raw DEFLATE of `data` (one fixed block of literals).
    fn raw_of(data: &[u8]) -> Vec<u8> {
        let mut w = BitW::new();
        fixed_block(&mut w, &data.iter().map(|&b| Tok::Lit(b)).collect::<Vec<_>>(), true);
        w.finish()
    }

    /// A gzip member of `data` with the optional header fields selected by `flags` (the
    /// header CRC16 is correct unless `bad_hcrc`).
    fn member(flags: u8, bad_hcrc: bool, data: &[u8]) -> Vec<u8> {
        let mut v = vec![0x1f, 0x8b, 8, flags, 0x12, 0x34, 0x56, 0x78, 0, 3];
        if flags & FEXTRA != 0 {
            let x = b"AB\x04\x00abcd";
            v.extend_from_slice(&(x.len() as u16).to_le_bytes());
            v.extend_from_slice(x);
        }
        if flags & FNAME != 0 {
            v.extend_from_slice(b"memory.raw\0");
        }
        if flags & FCOMMENT != 0 {
            v.extend_from_slice(b"a comment\0");
        }
        if flags & FHCRC != 0 {
            let c = crc32(&v) as u16 ^ bad_hcrc as u16;
            v.extend_from_slice(&c.to_le_bytes());
        }
        v.extend_from_slice(&raw_of(data));
        v.extend_from_slice(&crc32(data).to_le_bytes());
        v.extend_from_slice(&(data.len() as u32).to_le_bytes());
        v
    }

    #[test]
    fn codecs_gzip_levels() {
        for (k, g) in GZIP_LEVELS.iter().enumerate() {
            assert!(is_gzip(g));
            assert_eq!(decompress(g).unwrap(), TEXT, "vector {k}");
            // Truncation anywhere is an error.
            for n in 1..g.len() {
                assert!(decompress(&g[..n]).is_err(), "vector {k} truncated at {n}");
            }
            // Every bit of the CRC-32 and ISIZE fields is checked.
            for i in g.len() - 8..g.len() {
                for bit in 0..8 {
                    let mut v = g.to_vec();
                    v[i] ^= 1 << bit;
                    assert!(decompress(&v).is_err(), "vector {k} byte {i} bit {bit}");
                }
            }
            // MTIME, XFL and OS are informational.
            let mut v = g.to_vec();
            for b in &mut v[4..10] {
                *b ^= 0x5A;
            }
            assert_eq!(decompress(&v).unwrap(), TEXT);
        }
    }

    #[test]
    fn codecs_gzip_header_fields() {
        let data = &TEXT[..300];
        // Every combination of FTEXT, FHCRC, FEXTRA, FNAME, FCOMMENT.
        for flags in 0..32u8 {
            let m = member(flags, false, data);
            assert_eq!(decompress(&m).unwrap(), data, "flags {flags:#x}");
            for n in 1..m.len() {
                assert!(decompress(&m[..n]).is_err(), "flags {flags:#x} truncated at {n}");
            }
        }
        // Like python, the header CRC16 is not verified and reserved flag bits are ignored.
        assert_eq!(decompress(&member(FHCRC | FNAME, true, data)).unwrap(), data);
        assert_eq!(decompress(&member(0xE0 | FEXTRA, false, data)).unwrap(), data);
        // FEXTRA longer than the input, FNAME / FCOMMENT without their NUL.
        let mut v = vec![0x1f, 0x8b, 8, FEXTRA, 0, 0, 0, 0, 0, 3, 0xFF, 0xFF, 1, 2, 3];
        assert!(decompress(&v).is_err());
        v = vec![0x1f, 0x8b, 8, FNAME, 0, 0, 0, 0, 0, 3];
        v.extend_from_slice(b"no terminator");
        assert!(decompress(&v).is_err());
        v[3] = FCOMMENT;
        assert!(decompress(&v).is_err());
        // Unknown compression method.
        let mut m = member(0, false, data);
        m[2] = 7;
        assert!(decompress(&m).is_err());
    }

    #[test]
    fn codecs_gzip_members_and_padding() {
        assert_eq!(decompress(GZ).unwrap(), HELLO);
        let mut two = GZ.to_vec();
        two.extend_from_slice(&[0, 0, 0]);
        two.extend_from_slice(GZ);
        two.extend_from_slice(&[0, 0]);
        assert_eq!(decompress(&two).unwrap(), b"hello hello hello hello\nhello hello hello hello\n");
        // Members of every kind, including an empty one, back to back.
        let mut many = member(FNAME | FHCRC, false, b"first ").to_vec();
        many.extend_from_slice(&member(0, false, b""));
        many.extend_from_slice(GZIP_LEVELS[0]);
        many.push(0);
        many.extend_from_slice(&member(FEXTRA | FCOMMENT, false, b" last"));
        let mut want = b"first ".to_vec();
        want.extend_from_slice(TEXT);
        want.extend_from_slice(b" last");
        assert_eq!(decompress(&many).unwrap(), want);
        // python gzip.decompress: b"" -> b""; anything after the members but zero padding is
        // an error ("Not a gzipped file"), including a lone magic byte.
        assert_eq!(decompress(b"").unwrap(), b"");
        for tail in [&b"x"[..], b"\x1f", b"\x00\x00x", b"\x1f\x8b"] {
            let mut v = GZ.to_vec();
            v.extend_from_slice(tail);
            assert!(decompress(&v).is_err(), "tail {tail:?}");
        }
        assert!(decompress(b"\x1f").is_err());
        assert!(decompress(b"\x00\x00").is_err());
        assert!(!is_gzip(b"\x1f"));
        assert!(!is_gzip(b"BZh9"));
        let mut badcrc = GZ.to_vec();
        badcrc[GZ.len() - 8] ^= 1;
        assert!(decompress(&badcrc).is_err());
        for n in 1..GZ.len() {
            assert!(decompress(&GZ[..n]).is_err());
        }
        // A bad second member fails the whole call.
        let mut v = GZ.to_vec();
        let mut bad = GZ.to_vec();
        let k = bad.len() - 1;
        bad[k] ^= 1; // ISIZE
        v.extend_from_slice(&bad);
        assert!(decompress(&v).is_err());
    }

    #[test]
    fn codecs_gzip_garbage_never_panics() {
        let mut s = 0x0DDB_A11C_AFE0_F00Du64;
        let full = member(FEXTRA | FNAME | FCOMMENT | FHCRC, false, &TEXT[..500]);
        for round in 0..3000 {
            let mut v = if round % 2 == 0 { full.clone() } else { GZIP_LEVELS[round % GZIP_LEVELS.len()].to_vec() };
            for _ in 0..1 + round % 3 {
                let i = (xorshift(&mut s) as usize) % v.len();
                v[i] ^= 1 << (xorshift(&mut s) % 8);
            }
            if round % 5 == 0 {
                v.truncate((xorshift(&mut s) as usize) % v.len());
            }
            let _ = decompress(&v);
        }
    }
