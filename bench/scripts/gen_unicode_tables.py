#!/usr/bin/env python3
"""Generate src/yara/regex/unicode.rs from the running python's `re` / `_sre` so that
str-pattern semantics (\\w \\d \\s, IGNORECASE folding) match that python exactly."""
import os
import sys

import _sre
from re._casefix import _EXTRA_CASES

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))


def ranges(pred):
    out = []
    start = None
    for c in range(0x110000):
        ok = (not 0xD800 <= c <= 0xDFFF) and pred(c)
        if ok and start is None:
            start = c
        if not ok and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def fmt_ranges(name, rs):
    lines = ["pub static %s: &[(u32, u32)] = &[" % name]
    row = []
    for a, b in rs:
        row.append("(0x%x, 0x%x)" % (a, b))
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    return "\n".join(lines)


def main():
    word = ranges(lambda c: chr(c).isalnum() or c == 0x5F)
    digit = ranges(lambda c: chr(c).isdecimal())
    space = ranges(lambda c: chr(c).isspace())
    low = [(c, _sre.unicode_tolower(c)) for c in range(0x110000)
           if not 0xD800 <= c <= 0xDFFF and _sre.unicode_tolower(c) != c]
    out = ["// @generated by bench/scripts/gen_unicode_tables.py from python %s — do not edit." % sys.version.split()[0],
           "//! Unicode tables for python str-pattern semantics (`\\w`, `\\d`, `\\s`, simple",
           "//! lowercase mapping and sre's extra case-folding equivalences).",
           "",
           fmt_ranges("WORD", word), "", fmt_ranges("DIGIT", digit), "", fmt_ranges("SPACE", space), "",
           "/// (codepoint, simple lowercase) for every codepoint whose lowercase differs.",
           "pub static LOWER: &[(u32, u32)] = &["]
    row = []
    for a, b in low:
        row.append("(0x%x, 0x%x)" % (a, b))
        if len(row) == 6:
            out.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        out.append("    " + ", ".join(row) + ",")
    out.append("];")
    out.append("")
    out.append("/// sre `_EXTRA_CASES`: lowercase codepoint -> extra equivalent lowercase codepoints.")
    out.append("pub static EXTRA: &[(u32, &[u32])] = &[")
    for k in sorted(_EXTRA_CASES):
        out.append("    (0x%x, &[%s])," % (k, ", ".join("0x%x" % v for v in _EXTRA_CASES[k])))
    out.append("];")
    path = os.path.join(ROOT, "src", "yara", "regex", "unicode.rs")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote", path, len(word), len(digit), len(space), len(low), len(_EXTRA_CASES))


if __name__ == "__main__":
    main()
