#!/usr/bin/env python3
"""Learn / refine the 32-bit ARM (capstone CS_MODE_ARM) instruction-class spec by probing
capstone (see arm_learn.py / arm_driver.py for the commands).

Conditional instructions are learned in their AL (cond = 0b1110) form only: the engine renders a
conditional word no class claims as its AL twin with the condition suffix inserted into the
mnemonic ("F cond" spec record); words where that rule does not hold get their own classes
(or "invalid" classes).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import arm_driver  # noqa: E402
from arm_learn import HANDLERS  # noqa: E402

HANDLERS["invalid"] = lambda w, addr: None


class Arm32(arm_driver.ArchConfig):
    name = "arm"
    handler_classes = []
    reg_fields = (0, 8, 12, 16)
    rw = 4
    imm_fields = ((0, 12), (0, 8), (0, 4), (7, 5), (8, 4), (16, 4), (0, 24), (5, 2), (20, 1), (21, 2))
    rust_header = """//! 32-bit ARM instruction spec (generated by bench/scripts/gen_arm32_spec.py from probing the
//! capstone 5 oracle; grammar in bench/scripts/arm_spec.py). DO NOT EDIT BY HAND.

pub(crate) const SPEC: &str = r#\""""
    spec_records = ["F\tcond"]
    fold_cond = True


if __name__ == "__main__":
    arm_driver.main(Arm32(), sys.argv)
