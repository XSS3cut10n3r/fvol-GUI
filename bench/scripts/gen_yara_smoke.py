#!/usr/bin/env python3
"""Generate src/yara/smoke_cases.rs: fixed regression cases with expectations computed
by python `re` (regex engine) and yara-python (hex / regex strings), so that
`cargo test yara` checks semantics without needing python."""
import os
import random
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

import regex_diff  # noqa: E402
import yre_diff  # noqa: E402


def rs_bytes(b):
    out = []
    for c in b:
        if 32 <= c < 127 and c not in (0x22, 0x5c):
            out.append(chr(c))
        else:
            out.append("\\x%02x" % c)
    return 'b"' + "".join(out) + '"'


def rs_str(t):
    return '"' + t.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    r = random.Random(4242)
    out = ["// @generated by bench/scripts/gen_yara_smoke.py — do not edit.",
           "// (pattern, flags, haystack, expected finditer spans or \"ERR\")",
           "pub static RE_CASES: &[(&[u8], u32, &[u8], &str)] = &["]
    n = 0
    flag_choices = [0, 0, re.I, re.S, re.M, re.X]
    while n < 400:
        regex_diff.Gen.REGULAR = r.random() < 0.5
        p = regex_diff.gen_pattern(r)
        f = r.choice(flag_choices)
        h = regex_diff.gen_hay(r)
        e = regex_diff.guarded(regex_diff.py_iter, p, f, h)
        if e is None:
            continue
        out.append("    (%s, %d, %s, %s)," % (rs_bytes(p), f, rs_bytes(h), rs_str(e)))
        n += 1
    out.append("];")
    out.append("")
    out.append("// (kind, source, mods, data, expected \"off:len,...\" or \"ERR\")")
    out.append("pub static YRE_CASES: &[(&str, &[u8], &str, &[u8], &str)] = &[")
    n = 0
    while n < 300:
        kind = "hex" if r.random() < 0.45 else "re"
        if kind == "hex":
            src = yre_diff.gen_hex(r)
            mods = []
        else:
            src = yre_diff.ReGen(r, r.random() < 0.2).alt(0)
            mods = [m for m in ("nocase", "dotall", "wide", "ascii", "fullword") if r.random() < 0.15]
        dlen = r.choice([10, 40, 120])
        data = bytes(r.choice(b"abcA0- \n\x00") for _ in range(dlen))
        e = yre_diff.yara_matches(kind, src, mods, data)
        if e == "SCANERR":
            continue
        out.append("    (%s, %s, %s, %s, %s)," % (rs_str(kind), rs_bytes(src.encode()), rs_str(",".join(mods)), rs_bytes(data), rs_str(e)))
        n += 1
    out.append("];")
    path = os.path.join(ROOT, "src", "yara", "smoke_cases.rs")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
